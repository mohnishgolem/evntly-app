import type { Metadata } from "next";
import Link from "next/link";
import { notFound, redirect } from "next/navigation";
import { getCurrentUser } from "@/lib/data/user";
import { createClient } from "@/lib/supabase/server";
import { BOOKING_COLUMNS } from "@/lib/public-columns";
import { categoryLabel } from "@/lib/config";
import { formatAbn } from "@/lib/abn";
import { formatEventDate } from "@/lib/email";
import { PrintButton } from "@/components/print-button";

export const metadata: Metadata = {
  title: "Invoice",
  robots: { index: false, follow: false },
};

const INVOICEABLE = new Set(["confirmed", "completed"]);

function money(amount: number) {
  return amount.toLocaleString("en-AU", { style: "currency", currency: "AUD" });
}

// Issued by the vendor, generated by Evntly. Payments are made directly to
// the vendor (Evntly doesn't take payments yet), so this documents the
// booking and the vendor's ABN/GST details rather than a payment to us.
// Either party to the booking can open it: bookings RLS only returns rows
// where the caller is the client or the vendor.
export default async function BookingInvoicePage({
  params,
}: {
  params: Promise<{ id: string }>;
}) {
  const { id } = await params;
  const session = await getCurrentUser();
  if (!session) redirect(`/login?next=/bookings/${encodeURIComponent(id)}/invoice`);

  const supabase = await createClient();
  const { data: booking } = await supabase
    .from("bookings")
    .select(BOOKING_COLUMNS)
    .eq("id", id)
    .maybeSingle();
  if (!booking || !INVOICEABLE.has(booking.status)) notFound();

  const { data: vendor } = await supabase
    .from("service_providers")
    .select("name, abn, gst_registered, city")
    .eq("id", booking.provider_id)
    .maybeSingle();

  const isVendor = booking.provider_owner_user_id === session.user.id;
  const vendorName = vendor?.name ?? booking.provider_name ?? "Vendor";
  const total = Number(booking.total_price ?? 0);
  const taxInvoice = !!vendor?.abn && !!vendor?.gst_registered;
  const gst = taxInvoice ? total / 11 : 0;
  const invoiceNumber = `EV-${booking.id.replace(/-/g, "").slice(0, 8).toUpperCase()}`;
  const issued = new Date(booking.created_at).toLocaleDateString("en-AU", {
    day: "numeric",
    month: "long",
    year: "numeric",
  });
  const backHref = isVendor ? "/vendor-dashboard/bookings" : "/dashboard/bookings";

  return (
    <div className="mx-auto max-w-2xl px-4 py-8 print:max-w-none print:p-0">
      <div className="mb-6 flex items-center justify-between gap-3 print:hidden">
        <Link href={backHref} className="text-sm underline underline-offset-2">
          Back to bookings
        </Link>
        <PrintButton />
      </div>

      <article className="rounded-2xl border border-border bg-card p-6 sm:p-8 print:rounded-none print:border-0 print:p-0">
        <header className="mb-8 flex flex-wrap items-start justify-between gap-4">
          <div>
            <h1 className="text-2xl font-bold">{taxInvoice ? "Tax invoice" : "Invoice"}</h1>
            <p className="mt-1 text-sm text-muted-foreground">
              {invoiceNumber} · Issued {issued}
            </p>
          </div>
          <div className="text-right text-sm">
            <p className="font-semibold">{vendorName}</p>
            {vendor?.abn ? (
              <p>ABN {formatAbn(vendor.abn)}</p>
            ) : (
              <p className="text-muted-foreground">ABN not provided</p>
            )}
            {vendor?.city && <p className="text-muted-foreground">{vendor.city}</p>}
          </div>
        </header>

        <section className="mb-8 text-sm">
          <p className="mb-1 text-xs font-medium tracking-wide text-muted-foreground uppercase">Billed to</p>
          <p className="font-medium">{booking.client_label ?? "Customer"}</p>
          {booking.event_address && <p className="text-muted-foreground">{booking.event_address}</p>}
        </section>

        <table className="mb-6 w-full text-sm">
          <thead>
            <tr className="border-b border-border text-left text-xs text-muted-foreground uppercase">
              <th className="pb-2 font-medium">Description</th>
              <th className="pb-2 text-right font-medium">Amount</th>
            </tr>
          </thead>
          <tbody>
            <tr className="border-b border-border align-top">
              <td className="py-3">
                <p className="font-medium">{categoryLabel(booking.service_type)} services</p>
                <p className="text-muted-foreground">
                  Event on {formatEventDate(booking.event_date)}
                  {booking.event_time ? ` at ${booking.event_time}` : ""}
                  {booking.duration_hours ? ` · ${booking.duration_hours} hrs` : ""}
                </p>
              </td>
              <td className="py-3 text-right">{money(total)}</td>
            </tr>
          </tbody>
        </table>

        <div className="ml-auto max-w-xs space-y-1 text-sm">
          {taxInvoice && (
            <div className="flex justify-between text-muted-foreground">
              <span>GST included</span>
              <span>{money(gst)}</span>
            </div>
          )}
          <div className="flex justify-between text-base font-semibold">
            <span>Total{taxInvoice ? " (inc. GST)" : ""}</span>
            <span>{money(total)}</span>
          </div>
        </div>

        <footer className="mt-10 space-y-1 border-t border-border pt-4 text-xs text-muted-foreground">
          {!taxInvoice && vendor?.abn && <p>{vendorName} is not registered for GST. No GST has been charged.</p>}
          {!vendor?.abn && (
            <p>
              {isVendor
                ? "Add your ABN in Edit listing so clients can claim this as a business expense."
                : "This vendor hasn't added an ABN yet. Ask them for one if you need it for your records."}
            </p>
          )}
          <p>
            Payment is made directly to {vendorName}. Evntly connects you and generates this
            invoice for your records; it doesn&apos;t process this payment.
          </p>
          <p>Booking reference {booking.id}</p>
        </footer>
      </article>
    </div>
  );
}
