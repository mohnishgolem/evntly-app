import { writeFileSync } from "node:fs";
import { afterAll, describe, expect, it } from "vitest";
import { startSimulatedCall, svc } from "../sql/phone-agent-db";
import { SCENARIOS, type Scenario } from "../fixtures/phone-agent-scenarios";
import { checkPolicy, renderTranscript, runConversation, scriptedEngine, vendorLinesOf, type TranscriptEntry } from "@/lib/phone-agent/simulator";
import { estimateCallCost } from "@/lib/phone-agent/costs";

// The twelve simulated calls (+ a guardrail case), offline: each scripted
// conversation runs through the real tool path (runTool → phone_agent_tool in
// PGlite) and is checked against the conversation rules and the database.
// WRITE_PHONE_AGENT_REPORT=1 also writes docs/phone-agent/simulation-report.md.

type Result = { s: Scenario; transcript: TranscriptEntry[]; failures: string[]; seconds: number; costAud: number; row: Record<string, unknown> };
const results: Result[] = [];

async function simulate(s: Scenario): Promise<Result> {
  const { db, call, rpc, prospectId } = await startSimulatedCall(s);
  const sent: unknown[] = [];
  const transcript = await runConversation({
    engine: scriptedEngine(s.script),
    vendor: vendorLinesOf(s.script),
    call: { ref: call.ref, providerCallId: `sim_${s.id}` },
    deps: { rpc, sendLink: async (x) => { sent.push(x); return { ok: true }; } },
  });

  const { seconds, usdCents } = estimateCallCost(transcript);
  await svc(db, "select public.phone_agent_call_event($1, $2, 'call_ended', $3::jsonb)", [
    call.ref, `sim_${s.id}`, JSON.stringify({ duration_seconds: seconds, disconnection_reason: "agent_hangup", cost_usd_cents: usdCents }),
  ]);
  const row = (await db.query("select * from public.phone_calls where id = $1", [call.call_id])).rows[0];
  const followups = (await db.query("select kind from public.phone_followups order by id")).rows.map((r) => r.kind);
  const consents = (await db.query("select distinct kind from public.phone_consents order by kind")).rows.map((r) => r.kind);
  const suppressed = (await db.query("select count(*)::int n from public.phone_suppression")).rows[0].n > 0;
  const prospect = prospectId ? (await db.query("select do_not_contact, stage from public.vendor_prospects where id = $1", [prospectId])).rows[0] : null;

  const failures = [...checkPolicy(transcript).failures];
  const e = s.expect;
  const want = (cond: boolean, msg: string) => { if (!cond) failures.push(msg); };
  want(row.outcome === e.outcome, `outcome ${row.outcome} ≠ ${e.outcome}`);
  if (e.interest) want(row.interest === e.interest, `interest ${row.interest} ≠ ${e.interest}`);
  if (e.suppressed !== undefined) want(suppressed === e.suppressed, `suppressed ${suppressed}`);
  if (e.prospectDoNotContact !== undefined) want(prospect?.do_not_contact === e.prospectDoNotContact, "prospect do-not-contact");
  if (e.linkChannel !== undefined) want((row.link_channel ?? null) === e.linkChannel, `link channel ${row.link_channel}`);
  if (e.linkTo) want(row.link_to === e.linkTo, `link sent to ${row.link_to}`);
  if (e.linkChannel) want(sent.length === 1, `links sent: ${sent.length}`);
  if (e.followups) want(JSON.stringify(followups) === JSON.stringify(e.followups), `follow-ups ${followups}`);
  if (e.consents) for (const k of e.consents) want(consents.includes(k), `missing consent ${k}`);
  const refusals = transcript.filter((t) => t.who === "tool" && !t.ok).length;
  want(refusals === (e.toolRefusals ?? 0), `tool refusals ${refusals} ≠ ${e.toolRefusals ?? 0}`);
  if (e.transferred) want(transcript.some((t) => t.who === "tool" && t.name === "transfer_to_owner"), "not transferred");
  want(row.transcript === null, "transcript stored with recording off");

  return { s, transcript, failures, seconds, costAud: Math.round(usdCents * 1.55) / 100, row };
}

describe("phone agent: simulated conversations", () => {
  for (const s of SCENARIOS) {
    it(`${s.id} ${s.title}`, { timeout: 60_000 }, async () => {
      const r = await simulate(s);
      results.push(r);
      expect(r.failures).toEqual([]);
    });
  }
});

afterAll(() => {
  if (!process.env.WRITE_PHONE_AGENT_REPORT) return;
  const ordered = [...results].sort((a, b) => a.s.id.localeCompare(b.s.id));
  const totalCost = ordered.reduce((t, r) => t + r.costAud, 0);
  const lines = [
    "# Phone agent: simulated conversation report",
    "",
    `Generated by \`tests/unit/phone-agent-scenarios.test.ts\` (${new Date().toISOString().slice(0, 10)}). Offline: no calls, no providers, no production data.`,
    "",
    "Each conversation is a scripted reference call that follows the agent prompt. Every action the agent takes goes through the real",
    "`runTool()` → `phone_agent_tool()` path against the real migration (PGlite), and every agent line is checked against the",
    "conversation rules (AI disclosure, no guarantees or demand numbers, consent before links, opt-out ends the call, outcome recorded).",
    "These scripts test the rules and integrations; the wording a live model produces is tested with `scripts/phone-agent/simulate-live.ts`.",
    "",
    "| # | Scenario | Mode | Outcome | Interest | Est. length | Est. cost (A$) | Checks |",
    "|---|---|---|---|---|---|---|---|",
    ...ordered.map((r) => `| ${r.s.id.slice(0, 2)} | ${r.s.title} | ${r.s.mode} | ${r.row.outcome} | ${r.row.interest ?? "—"} | ${Math.floor(r.seconds / 60)}m ${r.seconds % 60}s | ${r.costAud.toFixed(2)} | ${r.failures.length ? "❌ " + r.failures.join("; ") : "✅ pass"} |`),
    "",
    `Estimated cost of all ${ordered.length} calls at pilot rates: A$${totalCost.toFixed(2)} (see docs/phone-agent/README.md for the rate card).`,
    "",
    ...ordered.flatMap((r) => [`## ${r.s.id}: ${r.s.title}`, "", `*${r.s.vendorName} (${r.s.category}), ${r.s.mode} call.* Persona: ${r.s.persona}`, "", "```text", renderTranscript(r.transcript), "```", ""]),
  ];
  writeFileSync("docs/phone-agent/simulation-report.md", lines.join("\n"));
});
